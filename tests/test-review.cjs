const assert = require('node:assert/strict');
require('../review-matrix.js');
const {auditCoverage, reviewHtml} = globalThis.DELTA_REVIEW;
assert.equal(typeof reviewHtml, 'function');
const partial = auditCoverage({source:'ieee',collected:25,expected_total:512,truncated:true,retrieval_mode:'visible_page_only',query:'dengue'});
assert.equal(partial.coverage_percent, 4.88);
assert.equal(partial.partial, true);
assert.equal(partial.exact_set_equivalence, 'not_verified');
assert.equal(partial.query_fidelity, 'not_equivalent_to_site_search');
const same = auditCoverage({source:'pubmed',collected:512,reported_total:512,query:'dengue'});
assert.equal(same.count_status, 'count_match_only');
assert.equal(same.exact_set_equivalence, 'not_verified');
assert.equal(same.partial, false);
const unknown = auditCoverage({source:'arxiv',collected:20,query:'abc'});
assert.equal(unknown.coverage_percent, null);
assert.equal(unknown.count_status, 'not_verified');
const html = reviewHtml([{source:'IEEE Xplore',identifier:'123',title:'<script>alert(1)</script>',abstract:'</script><script>alert(2)</script>',doi:'10.1109/demo',access_status:'open'}],{source:'ieee',audit:partial});
assert.ok(html.includes('DELTA — Matriz de revisão'));
assert.ok(!html.includes('</script><script>alert(2)</script>'), 'HTML must not allow script breakout');
assert.ok(html.includes('Salvar decisões JSON'));
assert.ok(html.includes('Exportar matriz anotada CSV'));
assert.ok(html.includes('count_status'));
assert.throws(()=>reviewHtml(null),/array/);
assert.throws(()=>reviewHtml(new Array(12001).fill({})),/12.000/);
console.log('PASS: local screening HTML and count/strategy audit');
